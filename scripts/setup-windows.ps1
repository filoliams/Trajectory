# Sets up a fresh clone of Trajectory on Windows: npm packages, the backend's Python venv,
# and the git-ignored files Expo and the scripts expect. Safe to run again.
#
#   git clone https://github.com/filoliams/Trajectory.git C:\dev\Trajectory
#   cd C:\dev\Trajectory; powershell -ExecutionPolicy Bypass -File scripts\setup-windows.ps1
#
# Keep the clone outside OneDrive: OneDrive turns node_modules and .venv into online-only
# placeholders, which breaks them. GitHub is the copy that syncs between machines.
param(
  # An old copy to take the git-ignored .env from, if this clone doesn't have one yet.
  [string]$EnvFrom = "$env:USERPROFILE\OneDrive\Desktop\Trajectory\.env"
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot

if ($root -like "*\OneDrive\*") {
  Write-Warning "This clone is inside OneDrive ($root). Move it somewhere like C:\dev first."
}

Write-Host "`n== App packages" -ForegroundColor Cyan
Push-Location "$root\app"
npm ci
if ($LASTEXITCODE) { throw 'npm ci failed in app/' }
# Generated by `expo start` and git-ignored; tsc needs it for CSS imports.
if (-not (Test-Path expo-env.d.ts)) {
  Set-Content expo-env.d.ts "/// <reference types=`"expo/types`" />`n`n// NOTE: This file should not be edited and should be in your git ignore" -NoNewline -Encoding utf8
}
Pop-Location

Write-Host "`n== Root packages" -ForegroundColor Cyan
Push-Location $root
npm ci
if ($LASTEXITCODE) { throw 'npm ci failed at the repo root' }
Pop-Location

Write-Host "`n== Backend venv (Python 3.11)" -ForegroundColor Cyan
Push-Location "$root\backend"
if (-not (Test-Path .venv\Scripts\python.exe)) {
  py -3.11 -m venv .venv
  if ($LASTEXITCODE) { throw 'Could not create the venv. Install Python 3.11 and try again.' }
}
.\.venv\Scripts\python -m pip install -q -r requirements.txt pytest==9.1.1
if ($LASTEXITCODE) { throw 'pip install failed' }
Pop-Location

Write-Host "`n== Secrets (.env)" -ForegroundColor Cyan
if (Test-Path "$root\.env") {
  Write-Host '.env already here.'
} elseif (Test-Path $EnvFrom) {
  Copy-Item $EnvFrom "$root\.env"
  Write-Host "Copied .env from $EnvFrom"
} else {
  Write-Warning ".env is missing. Copy it from your other machine (it is never in git); .env.example lists the keys."
}

Write-Host "`nDone. Start the app with: cd app; npx expo start --web" -ForegroundColor Green
